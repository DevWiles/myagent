package dev.wiles.myagent.plan;

/**
 * 一句话该怎么办：直接干，还是先拆个计划。
 *
 * <h3>为什么是三档而不是二选一</h3>
 * 和 {@code CommandGuard} 的三档风险判定同构，理由也一样：<b>静态判断不可能完美</b>。
 * 只有「干」和「规划」两个选项的话，判错就是硬错；中间留一档「问一句」，
 * 就把拿不准的成本转嫁成了一次追问——那是所有处理方式里最便宜的。
 *
 * <h3>拿不准时往哪偏</h3>
 * 往规划那边偏。因为判错的代价<b>不对称</b>：
 * <ul>
 *   <li>简单任务误判成要规划 —— 多一次规划调用和一次确认，<b>用户当场就能否决</b>，
 *       代价有限而且看得见</li>
 *   <li>复杂任务误判成直接干 —— ReAct 一路跑偏，改了一堆文件才发现方向错了，
 *       代价大而且发现得晚</li>
 * </ul>
 * 这和「未知命令一律归 NEEDS_APPROVAL」是同一个道理。
 */
public enum ExecutionMode {

    /** 一轮 ReAct 就能办完，别为它多花一次规划调用。 */
    DIRECT,

    /** 看不准。问一句「要不要先拆个计划」，零成本，比猜强。 */
    ASK,

    /** 明显是好几步的事，直接进规划。 */
    PLAN;

    public boolean needsPlan() {
        return this == PLAN;
    }
}
