package dev.wiles.myagent.plan;

/**
 * 计划的硬性上限。
 *
 * <p>单独拎一个类出来，是为了让<b>提示词和校验代码共用同一组数字</b>。
 * 提示词里写「拆成 5-10 个任务」、校验里写 {@code if (tasks.size() > 10)}，
 * 这两个 10 一旦分头维护，迟早会对不上——改了提示词忘了改校验，
 * 表现就是模型明明照做了却被程序打回来，这种 bug 极难联想到是常量不同步。
 *
 * <p>提示词那边会把这些值插值进去，见规划提示词的生成代码。
 */
public final class PlanLimits {

    /**
     * 一次规划最少拆几个任务。
     *
     * <p>下限的意义：拆成 1-2 个任务说明模型根本没在规划，那还不如直接走原来的 ReAct 循环，
     * 白搭一次规划调用。
     */
    public static final int MIN_TASKS = 5;

    /**
     * 一次规划最多拆几个任务。
     *
     * <p>上限的意义：模型很乐意把「改个错别字」拆成 20 步。任务越多，
     * 跑得越久、烧的 token 越多，而且中间任何一环偏了，后面全歪。
     */
    public static final int MAX_TASKS = 10;

    /**
     * 一次<b>子规划</b>最多拆几个任务。比根计划的上限小得多。
     *
     * <p>这个数字是实跑打出来的：第一次真机跑 /plan 时，一个「先摸清情况」的探路任务
     * 一口气拆出 10 个子任务，整张图从 7 个膨胀到 17 个，跑了近两分钟。
     * 探路任务的产出本该是「接下来这几步」，不是另一份完整计划——
     * 真有那么多事要做，说明根计划那一层就拆错了。
     */
    public static final int MAX_SUB_TASKS = 5;

    /**
     * 一次<b>重规划</b>最多补几个任务。
     *
     * <p>比根计划的上限小：重规划是在已经做成的一堆事情之上补救，不是从头再来一遍。
     * 真需要十个任务才能补上，说明失败的根子在原计划的思路上，
     * 那种情况下继续自动往下跑只会越跑越偏，不如把结果如实交给用户。
     */
    public static final int MAX_REPLAN_TASKS = 6;

    /**
     * 一次计划最多重规划几轮。
     *
     * <p><b>只给一次。</b>第一次失败常常是「这条路走不通，换一条」，模型确实能补救；
     * 补救又失败，说明它对这件事的理解就不对，再来第三第四轮只是拿同一个误解
     * 反复换皮，每一轮都是真金白银的调用。与其烧到天荒地老，不如把「跑到哪儿、
     * 为什么停」如实报给用户——人看一眼往往当场就知道问题在哪。
     */
    public static final int MAX_REPLANS = 1;

    /**
     * 任务的最大深度。0 是规划直接产出的根任务，1 是 {@link TaskType#PLANNING}
     * 任务再拆出来的子任务。
     *
     * <p>为什么卡死在 1：PLANNING 任务的产出是新任务，子任务里要是还能有 PLANNING，
     * 就能一层层套到天荒地老，而每一层都是一次真金白银的模型调用。
     * 允许一层，是为了应付「这块现在看不清、得先摸一摸再拆」的情况；
     * 允许两层，收益说不清，风险却是指数级的。
     */
    public static final int MAX_DEPTH = 1;

    private PlanLimits() {
    }
}
