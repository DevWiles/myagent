package dev.wiles.myagent.plan;

/**
 * 任务的类型。
 *
 * <p>这不是给人看的分类标签，它要真的影响执行，否则就是个装饰字段。目前要它管三件事：
 * <ol>
 *   <li><b>放开哪些工具</b>。{@link #FILE_READ} 拿不到写工具，模型就算想偏了也写不坏东西
 *       ——这比「执行到危险命令时弹审批」更早一道闸门。</li>
 *   <li><b>能不能并发</b>。只读和纯推理的任务天然可以同时跑，动文件、跑命令的不行。</li>
 *   <li><b>界面怎么显示</b>。计划面板靠它上图标和颜色。</li>
 * </ol>
 *
 * <p>类型由规划阶段的模型自己选，所以每一项的含义都得写清楚——
 * 这段注释最终会以另一种形式出现在规划提示词里。
 */
public enum TaskType {

    /**
     * 规划任务：把一件还看不清的事拆成更小的任务。
     *
     * <p>它的产出不是代码也不是结论，而是<b>新的任务</b>——意味着 DAG 在执行过程中会长大。
     * 这是六种类型里唯一会反过来改图的，调度器要为它单开一条路。
     */
    PLANNING,

    /** 读取文件、列目录、找代码。只读，不改任何东西。 */
    FILE_READ,

    /** 写入文件：新建或修改。 */
    FILE_WRITE,

    /** 执行命令：跑脚本、装依赖、调构建工具。 */
    COMMAND,

    /** 分析结果：把上游拿到的材料想明白，产出结论。不碰文件系统。 */
    ANALYSIS,

    /** 验证结果：跑测试、跑构建，确认前面做的事是不是真的成了。 */
    VERIFICATION
}
